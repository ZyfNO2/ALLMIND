import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createServer } from 'node:http';
import { chromium } from '@playwright/test';
import { build } from 'esbuild';
import { FileBookRepository } from '../../dist/memory/file-book-repository.js';
import { BookRuntime } from '../../dist/app/book-runtime.js';
import { BookCredentials } from '../../dist/management/book-credentials.js';
import { startBookServer } from '../../dist/management/book-server.js';

test('model discovery exposes a selectable list, preserves manual input and saves only explicitly', { timeout: 60000 }, async t => {
  const root = resolve('.local/memory-book-tests'); mkdirSync(root, { recursive: true });
  const directory = mkdtempSync(join(root, 'model-settings-'));
  const repository = new FileBookRepository(directory);
  const calls = [];
  const runtime = new BookRuntime(repository, { async complete(_binding, messages) { calls.push(messages); return '<ruby>你好<rt>こんにちは</rt></ruby><img src=x onerror="window.rubyUnsafe=true">'; } });
  const server = await startBookServer({ runtime, credentials: new BookCredentials(join(directory, 'credentials')), uiRoot: resolve('management') });
  let requests = 0;
  const provider = createServer((request, response) => {
    assert.equal(request.url, '/v1/models');
    assert.equal(request.headers.authorization, 'Bearer settings-fixture-key');
    requests++;
    response.setHeader('Content-Type', 'application/json');
    response.end(JSON.stringify({ data: [{ id: 'fixture-a' }, { id: 'fixture-b' }] }));
  });
  await new Promise(done => provider.listen(0, '127.0.0.1', done));
  let browser;
  t.after(async () => { await browser?.close(); await server.close(); provider.closeAllConnections(); await new Promise(done => provider.close(done)); repository.close(); });
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage(); page.setDefaultTimeout(8000);
  await page.goto(server.url);
  await page.getByRole('link', { name: '设置', exact: true }).click();
  const card = page.locator('.mb-model-card').filter({ has: page.getByRole('heading', { name: '文字主模型', exact: true }) });
  await card.getByLabel('启用', { exact: true }).check();
  await card.getByLabel('端点', { exact: true }).fill(`http://127.0.0.1:${provider.address().port}/v1`);
  await card.getByLabel('API Key', { exact: true }).fill('settings-fixture-key');
  await card.getByRole('button', { name: '获取模型', exact: true }).click();
  await page.getByText('已获取 2 个模型；可选择或手动输入。', { exact: true }).waitFor();
  const choices = card.getByLabel('已获取的模型', { exact: true });
  await choices.selectOption('fixture-a');
  assert.equal(await card.getByLabel('模型', { exact: true }).inputValue(), 'fixture-a');
  assert.equal(await card.getByRole('button', { name: '测试连接', exact: true }).isEnabled(), true);
  assert.equal(repository.loadConfig().mainModel, null);
  await card.getByLabel('模型', { exact: true }).fill('manual-model');
  await card.getByRole('button', { name: '获取模型', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.mb-page-fieldset').disabled);
  assert.equal(await card.getByLabel('模型', { exact: true }).inputValue(), 'manual-model');
  assert.equal(await choices.inputValue(), '');
  await choices.selectOption('fixture-b');
  assert.equal(calls.length, 0, 'Discovery must not call a chat model');
  await page.getByLabel('回复语言', { exact: true }).selectOption('zh-ja-ruby');
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByText('设置已保存并生效。', { exact: true }).waitFor();
  assert.equal(repository.loadConfig().mainModel.model, 'fixture-b');
  assert.equal(repository.loadConfig().replyLanguage, 'zh-ja-ruby');
  await page.reload();
  assert.equal(await page.getByLabel('回复语言', { exact: true }).inputValue(), 'zh-ja-ruby');
  await page.getByRole('link', { name: '首页', exact: true }).click();
  await page.getByLabel('聊天消息').fill('你好');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await page.locator('.mb-answer ruby rt').waitFor();
  assert.equal(await page.locator('.mb-answer ruby rt').innerText(), 'こんにちは');
  assert.equal(await page.locator('.mb-answer img').count(), 0, 'HTML other than safe Ruby pairs is text');
  assert.equal(await page.evaluate(() => window.rubyUnsafe), undefined);
  assert.equal(calls.length, 1);
  assert.match(JSON.stringify(calls[0]), /中文正文.*日文/u);
  await page.getByRole('link', { name: '设置', exact: true }).click();
  assert.equal(requests, 2);
  await card.getByRole('button', { name: '获取模型', exact: true }).click();
  await choices.waitFor();
  await card.getByLabel('端点', { exact: true }).fill('http://127.0.0.1:12345/v1');
  assert.equal(await choices.count(), 0, 'Changing endpoint must clear stale choices');
});

test('desktop Ruby renderer creates annotations without interpreting other HTML', async t => {
  const bundle = await build({ entryPoints: ['core/ruby-text.ts'], bundle: true, write: false, format: 'iife', globalName: 'RubyText' });
  const browser = await chromium.launch({ headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage();
  await page.setContent('<div id="answer"></div>');
  await page.addScriptTag({ content: bundle.outputFiles[0].text });
  await page.evaluate(() => RubyText.renderRubyText(document.getElementById('answer'), '<ruby>你好<rt>こんにちは</rt></ruby><img src=x onerror="window.rubyUnsafe=true">'));
  assert.equal(await page.locator('#answer ruby rt').innerText(), 'こんにちは');
  assert.equal(await page.locator('#answer img').count(), 0);
  assert.equal(await page.evaluate(() => window.rubyUnsafe), undefined);
  assert.match(await page.locator('#answer').textContent(), /<img src=x/);
});
