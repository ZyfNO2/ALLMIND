import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdirSync,mkdtempSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {chromium} from '@playwright/test';
import {FileBookRepository} from '../../dist/memory/file-book-repository.js';
import {FactWikiService} from '../../dist/memory/fact-wiki.js';
import {BookRuntime} from '../../dist/app/book-runtime.js';
import {BookCredentials} from '../../dist/management/book-credentials.js';
import {startBookServer} from '../../dist/management/book-server.js';
import {emptyEntry} from '../../dist/contracts/memory-book.js';

test('source revoke previews impact, cancel sends nothing, stale confirmation refuses, final confirmation submits once',{timeout:45000},async t=>{
  mkdirSync('.local/ui-v4/tests',{recursive:true});
  const directory=resolve(mkdtempSync('.local/ui-v4/tests/revoke-confirm-')),repository=new FileBookRepository(directory);
  const scope={characterId:'aika',pairingId:'local-user',sessionId:'web-chat'},wiki=new FactWikiService(repository);
  const preview=wiki.preview(scope,{sourceId:'confirm-source',title:'确认测试来源',text:'饮品偏好：乌龙茶',private:true});
  wiki.apply(scope,preview.id,'seed-source');
  const runtime=new BookRuntime(repository,{async complete(){throw Error('Unexpected model call')}});
  const server=await startBookServer({runtime,credentials:new BookCredentials(join(directory,'credentials')),uiRoot:resolve('management')});
  const browser=await chromium.launch({headless:true});
  t.after(async()=>{await browser.close();await server.close();repository.close()});
  const page=await browser.newPage();page.setDefaultTimeout(10000);
  let posts=0;page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/wiki/revoke'))posts++});
  await page.goto(server.url);await page.getByRole('link',{name:'记忆',exact:true}).click();
  await page.getByRole('button',{name:'日常整理'}).click();await page.getByText('高级工具与来源',{exact:true}).click();await page.getByText('来源与版本',{exact:true}).click();
  await page.getByRole('button',{name:'撤销来源',exact:true}).click();
  assert.equal(repository.snapshot(scope).wikiSources[0].enabled,true);
  const dialog=page.getByRole('dialog',{name:'确认撤销来源'});await dialog.waitFor();
  assert.match(await dialog.textContent(),/确认测试来源/);assert.match(await dialog.textContent(),/原文.*保留/);
  await page.keyboard.press('Escape');assert.equal(posts,0);
  await page.getByRole('button',{name:'撤销来源',exact:true}).click();
  await dialog.getByRole('button',{name:'取消',exact:true}).click();assert.equal(posts,0);
  await page.getByRole('button',{name:'撤销来源',exact:true}).click();
  const snapshot=repository.snapshot(scope);repository.commit(scope,{upsert:[emptyEntry('changed-story','story','并发修订','合成作者设定')]},snapshot.revision,'change-before-confirm');
  assert.ok(repository.snapshot(scope).revision>snapshot.revision);
  const conflict=page.waitForResponse(r=>r.url().endsWith('/wiki/revoke'));
  await dialog.getByRole('button',{name:'确认撤销来源',exact:true}).click();
  assert.equal((await conflict).status(),409);
  await page.getByRole('alert').filter({hasText:'Book 已修改，请回读当前版本。'}).waitFor();
  assert.equal(repository.snapshot(scope).wikiSources[0].enabled,true);
  await page.reload();await page.getByRole('button',{name:'日常整理'}).click();await page.getByText('高级工具与来源',{exact:true}).click();await page.getByText('来源与版本',{exact:true}).click();
  await page.getByRole('button',{name:'撤销来源',exact:true}).click();
  const before=posts;
  await dialog.getByRole('button',{name:'确认撤销来源',exact:true}).click();
  await page.getByText(/已撤销/).first().waitFor();
  assert.equal(posts,before+1);assert.equal(repository.snapshot(scope).wikiSources[0].enabled,false);
});
