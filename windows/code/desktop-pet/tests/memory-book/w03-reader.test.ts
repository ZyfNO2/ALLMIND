function png(): Buffer {
  const crc32 = (buffer: Buffer): number => { let crc = 0xffffffff; for (const byte of buffer) { crc ^= byte; for (let bit = 0; bit < 8; bit += 1) crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1; } return (crc ^ 0xffffffff) >>> 0; };
  const chunk = (type: string, body: Buffer): Buffer => { const head = Buffer.alloc(4); head.writeUInt32BE(body.length); const typed = Buffer.concat([Buffer.from(type, 'ascii'), body]); const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(typed)); return Buffer.concat([head, typed, crc]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(4, 0); ihdr.writeUInt32BE(3, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IEND', Buffer.alloc(0))]);
}

test('reader text drops scripts and the wiki reader hides restricted material', async () => {
  assert.equal(readableText('<img src=x onerror="alert(1)"><script>alert(1)</script><a href="javascript:alert(1)">点</a>正文'), '点正文');
  const root = mkdtempSync(join(tmpdir(), 'w03-reader-'));
  const repository = new FileBookRepository(root);
  const scope = { characterId: 'aika', pairingId: 'local-user', sessionId: 'web-chat' };
  const resources = new BookResourceService(new FileResourceStore({ directory: join(root, 'resources') }));
  const signal = new AbortController().signal;
  const picture = await resources.receiveUpload(scope, { name: '章节/图.png', mime: 'image/png' }, png(), 'pic', signal);
  const left = await resources.receiveUpload(scope, { name: '同名.md', mime: 'text/markdown' }, new TextEncoder().encode('甲'), 'dup-a', signal);
  const right = await resources.receiveUpload(scope, { name: '同名.md', mime: 'text/markdown' }, new TextEncoder().encode('乙'), 'dup-b', signal);
  const html = await resources.receiveUpload(scope, { name: '恶意.html', mime: 'text/html' }, new TextEncoder().encode('<script>alert(1)</script><p>可见</p>'), 'html', signal);
  const tea = emptyEntry('tea', 'lore', '茶', `角色喜欢乌龙茶。 ![立绘](resource:${picture.id}) [重复](同名.md) [外链](https://example.test/a) [中文图](${encodeURIComponent('章节/图.png')})`);
  tea.sourceRefs = ['note-tea']; tea.related = ['keys'];
  const keys = emptyEntry('keys', 'memory', '输入', '检测到键盘输入');
  keys.sourceRefs = ['note-keys']; keys.pairingId = scope.pairingId; keys.origin = 'observed';
  const secret = emptyEntry('secret-name', 'lore', '秘密', '未揭露的真名是星隐');
  secret.sourceRefs = ['note-secret']; secret.organization = { domain: 'rp', evidenceStatus: 'source_asserted' };
  secret.knowledge = { worldId: 'world-a', branch: 'main', chapter: 9, awareness: 'unknown' };
  const extra = emptyEntry('extra-note', 'lore', '补充', '角色也收藏茶杯。');
  extra.sourceRefs = ['note-extra'];
  const other = emptyEntry('other-world', 'lore', '别章', '第九章密语星门');
  other.sourceRefs = ['note-other']; other.knowledge = { worldId: 'world-a', branch: 'main', chapter: 9, awareness: 'experienced' };
  repository.commit(scope, { upsert: [tea, keys, secret, other, extra] }, 0, 'seed');
  const reader = new WikiReader(repository, new FactWikiService(repository), resources);
  const view = { worldId: 'world-a', branch: 'main', cutoff: 1 };
  const page = reader.read(scope, { view, limit: 20 });
  const packed = JSON.stringify(page);
  assert.equal(packed.includes('星隐'), false);
  assert.equal(packed.includes('星门'), false);
  const catalog = reader.read(scope, { view, limit: 2 });
  assert.equal(catalog.pages.length, 2);
  assert.equal(catalog.nextCursor, catalog.pages[1]?.id);
  const rest = reader.read(scope, { view, limit: 2, cursor: catalog.nextCursor! });
  assert.equal(rest.pages.some(item => catalog.pages.some(first => first.id === item.id)), false);
  const teaPage = page.pages.find(item => item.title === '茶');
  assert.ok(teaPage);
  const opened = reader.read(scope, { view, pageId: teaPage.id, limit: 20 });
  assert.equal(opened.document?.assets.some(asset => asset.resourceId === picture.id && asset.state === 'ready'), true);
  assert.equal(opened.document?.links.some(link => link.state === 'duplicate'), true);
  assert.equal(opened.document?.links.some(link => link.state === 'external'), true);
  assert.equal(opened.document?.body.includes('<script'), false);
  assert.equal(opened.graph.edges.every(edge => edge.experience === false && edge.basis.length > 0), true);
  assert.equal(opened.timeline.some(item => item.id === 'keys' && item.activity === 'input' && item.label === '输入活动'), true);
  assert.equal(JSON.stringify(opened.timeline).includes('工作'), false);
  const htmlDoc = reader.read(scope, { pageId: `resource:${html.id}` });
  assert.equal(htmlDoc.document?.body.includes('alert'), false);
  assert.equal(htmlDoc.document?.body.includes('可见'), true);
  resources.revoke(scope, picture.id, picture.revision, 'revoke-pic');
  const revoked = reader.read(scope, { view, pageId: opened.document!.id });
  assert.equal(revoked.document?.assets.some(asset => asset.resourceId === picture.id && asset.state === 'revoked'), true);
  await assert.rejects(async () => { reader.read({ ...scope, characterId: 'other' }, { pageId: opened.document!.id }); }, (error: unknown) => (error as { code?: string }).code === 'not_found');
  assert.equal(left.id !== right.id, true);
  repository.close();
  rmSync(root, { recursive: true, force: true });
});
