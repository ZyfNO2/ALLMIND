import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createServer } from 'node:http';
import { chromium } from '@playwright/test';
import { FileBookRepository } from '../../dist/memory/file-book-repository.js';
import { BookRuntime } from '../../dist/app/book-runtime.js';
import { BookHttpModel } from '../../dist/providers/book-model.js';
import { BookCredentials } from '../../dist/management/book-credentials.js';
import { startBookServer } from '../../dist/management/book-server.js';

test('four AIKI concepts: compile Wiki, consume chat, record Memory, commit event/state and revoke source through UI', { timeout: 90000 }, async t => {
  const root = resolve('.local/memory-book-tests'); mkdirSync(root, { recursive: true });
  const directory = mkdtempSync(join(root, 'cir-browser-')), repo = new FileBookRepository(directory), calls = [], errors = [];
  const upstream = createServer(async (request, response) => {
    let raw = ''; for await (const chunk of request) raw += chunk;
    const payload = JSON.parse(raw); calls.push(payload);
    const content = payload.model === 'wiki-fixture' ? JSON.stringify({ claims: [{ subject: '用户', predicate: '饮品偏好', value: '乌龙茶', quote: '用户喜欢乌龙茶。' }] }) : '这是 HTTP fixture 回答。';
    response.writeHead(200, { 'Content-Type': 'application/json' }); response.end(JSON.stringify({ choices: [{ finish_reason: 'stop', message: { content } }] }));
  });
  await new Promise(done => upstream.listen(0, '127.0.0.1', done));
  const binding = { baseUrl: `http://127.0.0.1:${upstream.address().port}/v1`, model: 'chat-fixture', credentialId: 'local-no-auth', inputTokens: 8192, outputTokens: 1024 };
  const config = repo.loadConfig(); repo.commitConfig({ ...config, mainModel: binding, fastModel: { ...binding, model: 'wiki-fixture' }, recall: { ...config.recall, mode: 'off' } }, 0, 'seed');
  const runtime = new BookRuntime(repo, new BookHttpModel(async () => ''));
  const server = await startBookServer({ runtime, credentials: new BookCredentials(join(directory, 'credentials')), uiRoot: resolve('management') });
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); await server.close(); upstream.closeAllConnections(); await new Promise(done => upstream.close(done)); repo.close(); });
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } }); page.setDefaultTimeout(15000); page.on('pageerror', error => errors.push(error.message));
  await page.goto(server.url); await page.getByRole('link', { name: '记忆', exact: true }).click();
  // V4 nests the fact wiki inside the collapsed 高级工具与来源 panel on the memory page.
  await page.getByRole('button',{name:'日常整理'}).click();await page.getByText('高级工具与来源', { exact: true }).click();
  const wiki = page.getByRole('region', { name: '事实 Wiki' });
  await wiki.getByText('整理事实来源', { exact: true }).click();
  await wiki.getByLabel('Wiki 资料名称', { exact: true }).fill('AIKI 工程');
  await wiki.getByLabel('Wiki 事实资料', { exact: true }).fill('# AIKI\n存储：本地文件');
  await wiki.getByRole('button', { name: '预览事实整理', exact: true }).click();
  await wiki.getByRole('button', { name: '确认事实并应用', exact: true }).click();
  await wiki.getByText('AIKI · 1 条事实', { exact: true }).waitFor(); assert.equal(calls.length, 0, 'declaration ingest has no model call');
  await wiki.getByLabel('Wiki 资料名称', { exact: true }).fill('用户'); await wiki.getByLabel('Wiki 事实资料', { exact: true }).fill('用户喜欢乌龙茶。');
  await wiki.getByRole('button', { name: 'AI 整理并预览', exact: true }).click();
  await wiki.getByRole('button', { name: '确认事实并应用', exact: true }).click(); await wiki.getByText('用户 · 1 条事实', { exact: true }).waitFor();
  assert.equal(calls.length, 1); assert.equal(calls[0].model, 'wiki-fixture'); assert.equal(repo.snapshot(runtime.scope('aika', 'web-chat', 'other')).entries.length, 0);
  await page.getByRole('link', { name: '首页', exact: true }).click();
  await page.getByLabel('聊天消息', { exact: true }).fill('AIKI 的存储是啥？我已到机库'); await page.getByRole('button', { name: '发送', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('textarea[aria-label="聊天消息"]').value === '');
  assert.ok(calls.at(-1).messages.some(message => message.content.includes('本地文件')));
  await page.getByRole('link', { name: '记忆', exact: true }).click();
  await page.getByRole('button',{name:'日常整理'}).click();await page.getByText('高级工具与来源', { exact: true }).click();
  const memory = page.getByRole('region', { name: '共同记忆' }); await memory.getByRole('button', { name: '记录最近一次共同聊天', exact: true }).click();
  await page.getByRole('button', { name: '列表与编辑', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.mb-entry').length === 3);
  await page.getByRole('button',{name:'日常整理'}).click();
  const tools = page.locator('details.mb-memory-tools');
  if (!(await tools.evaluate(node => node.open))) await tools.locator('summary').first().click();
  await memory.getByText('依据记忆更新当前状态', { exact: true }).click(); await memory.getByLabel('状态新值', { exact: true }).fill('机库');
  await memory.getByRole('button', { name: '预览状态变化', exact: true }).click(); await memory.getByRole('button', { name: '确认事件与状态', exact: true }).click();
  await memory.getByText(/地点：机库 · 依据/).waitFor();
  const scope = runtime.scope('aika', 'web-chat'); assert.equal(runtime.state.view(scope).states.length, 1); assert.equal(runtime.state.view(scope).events.length, 1);
  assert.equal(repo.snapshot(scope).entries.filter(entry => entry.type === 'memory').length, 2, 'shared chat and event belong to Memory');
  assert.ok(!runtime.imports.export(scope).text.includes('乌龙茶'));
  await wiki.getByText('来源与版本', { exact: true }).click(); await wiki.getByRole('button', { name: '撤销来源', exact: true }).first().click();
  // R1 gates source revocation behind a confirmation dialog (preview/cancel paths are covered by source-revoke-confirm.browser.test.mjs).
  await page.getByRole('dialog', { name: '确认撤销来源' }).getByRole('button', { name: '确认撤销来源', exact: true }).click();
  await page.waitForFunction(() => ![...document.querySelectorAll('summary')].some(node => node.textContent === 'AIKI · 1 条事实'));
  await wiki.getByRole('button', { name: '检查 Wiki', exact: true }).click(); await wiki.getByText(/来源已撤销或修订/).waitFor();
  const evidence = resolve('../../../validation/output/character-intelligence-runtime/evidence'); mkdirSync(evidence, { recursive: true });
  await page.screenshot({ path: join(evidence, 'wiki-memory-state.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(evidence, 'wiki-narrow.png'), fullPage: true });
  const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].map(node => ({ tag: node.tagName, class: node.className, text: node.textContent.slice(0, 100), width: node.getBoundingClientRect().width, right: node.getBoundingClientRect().right })).filter(node => node.right > innerWidth + 1).slice(-12));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'small view must not overflow: ' + JSON.stringify(overflow)); assert.deepEqual(errors, []);
});
